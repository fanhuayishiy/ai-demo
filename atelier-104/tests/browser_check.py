"""Run against the local preview: python tests/browser_check.py"""
from pathlib import Path
import json
from playwright.sync_api import sync_playwright, expect

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'qa'
OUT.mkdir(exist_ok=True)
with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, args=['--enable-webgl', '--use-gl=angle', '--use-angle=swiftshader'])
    page = browser.new_page(viewport={'width':1440,'height':1000}, device_scale_factor=1)
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto('http://127.0.0.1:5173/')
    page.wait_for_load_state('networkidle')
    expect(page.locator('canvas')).to_be_visible()
    expect(page.locator('#scene-error')).to_be_hidden()
    expect(page.locator('#preview-test-status')).to_have_text('自动检测中')
    expect(page.locator('#start-test, #preview-start-test')).to_have_count(0)
    page.keyboard.press('a')
    expect(page.locator('#preview-tested-count')).to_have_text('1')
    page.locator('#preview-clear-test').click()
    expect(page.locator('#preview-tested-count')).to_have_text('0')
    page.screenshot(path=str(OUT/'desktop.png'),full_page=True)
    page.locator('[data-theme="night"]').click()
    expect(page.locator('#theme-name')).to_have_text('午夜航行')
    page.locator('[data-theme="sand"]').click()
    expect(page.locator('[data-color="accent"]')).to_have_value('#c97c5e')
    page.locator('[data-shell="#272f40"]').click()
    expect(page.locator('#shell-hex')).to_have_text('#272F40')
    page.locator('[data-panel="structure"]').click()
    page.locator('#explode').click()
    expect(page.locator('#explode-range')).to_have_value('100')
    page.wait_for_timeout(900)
    page.screenshot(path=str(OUT/'exploded.png'),full_page=True)
    page.locator('#explode').click()
    page.locator('[data-light="static"]').click()
    page.locator('#switch').select_option('tactile')
    page.locator('#save').click()
    page.locator('#design-name').fill('浏览器验证方案')
    page.locator('#save-form button[type="submit"]').click()
    expect(page.locator('#save-count')).to_have_text('1')
    page.reload()
    expect(page.locator('#theme-name')).to_have_text('沙丘日落')
    expect(page.locator('#save-count')).to_have_text('1')
    page.locator('[data-page="saved"]').click()
    expect(page.locator('.saved-card h2')).to_have_text('浏览器验证方案')
    with page.expect_download() as dl:
        page.locator('.saved-card .export').click()
    assert json.loads(Path(dl.value.path()).read_text(encoding='utf-8'))['config']['accent']=='#c97c5e'
    page.locator('.saved-card .load').click()
    expect(page.locator('#design-page')).to_be_visible()
    page.locator('[data-page="test"]').click()
    expect(page.locator('.test-key')).to_have_count(104)
    # Mouse interaction never counts toward physical keyboard coverage.
    page.locator('[data-code="KeyA"]').click()
    expect(page.locator('#tested-count')).to_have_text('0')
    page.locator('#test-keyboard').focus()
    page.keyboard.down('a')
    page.keyboard.down('s')
    expect(page.locator('#held-count')).to_have_text('2')
    expect(page.locator('#max-count')).to_have_text('2')
    page.keyboard.down('s')  # auto-repeat must not inflate the count
    expect(page.locator('#press-count')).to_have_text('2')
    page.keyboard.up('a')
    page.keyboard.up('s')
    page.keyboard.press('ShiftLeft')
    page.keyboard.press('ShiftRight')
    page.keyboard.press('NumpadEnter')
    expect(page.locator('#tested-count')).to_have_text('5')
    expect(page.locator('[data-code="NumpadEnter"]')).to_have_class('test-key accent tested')
    expect(page.locator('#event-code')).to_have_text('NumpadEnter')
    expect(page.locator('#event-location')).to_have_text('数字区')
    page.keyboard.down('d')
    page.evaluate("window.dispatchEvent(new Event('blur'))")
    expect(page.locator('#held-count')).to_have_text('0')
    page.keyboard.up('d')
    page.keyboard.press('z')
    expect(page.locator('#tested-count')).to_have_text('7')
    with page.expect_download() as dl:
        page.locator('#export-test').click()
    result=json.loads(Path(dl.value.path()).read_text(encoding='utf-8'))
    assert result['total']==7 and result['maxConcurrent']==2
    page.screenshot(path=str(OUT/'keyboard-test.png'),full_page=True)
    page.locator('#clear-test').click()
    expect(page.locator('#tested-count')).to_have_text('0')
    page.locator('[data-page="design"]').click()
    # The same real-key detection session can run directly on the 3D model.
    expect(page.locator('#preview-test-status')).to_have_text('自动检测中')
    page.locator('#scene').focus()
    page.wait_for_timeout(200)
    before = page.locator('canvas').screenshot()
    page.keyboard.down('a')
    page.keyboard.down('s')
    expect(page.locator('#preview-held-count')).to_have_text('2')
    expect(page.locator('#preview-tested-count')).to_have_text('2')
    page.keyboard.down('a')
    expect(page.locator('#press-count')).to_have_text('2')
    page.wait_for_timeout(200)
    pressed = page.locator('canvas').screenshot()
    page.keyboard.up('a')
    page.keyboard.up('s')
    page.wait_for_timeout(200)
    released = page.locator('canvas').screenshot()
    assert before != pressed and before != released and pressed != released, '3D model must visibly distinguish untested, held and tested keys'
    for key in ['ShiftLeft','ShiftRight','NumpadEnter']:
        page.keyboard.press(key)
    expect(page.locator('#preview-tested-count')).to_have_text('5')
    expect(page.locator('#preview-max-count')).to_have_text('2')
    page.locator('[data-page="test"]').click()
    expect(page.locator('#tested-count')).to_have_text('5')
    expect(page.locator('#test-state')).to_contain_text('自动检测中')
    page.locator('[data-page="design"]').click()
    page.keyboard.press('z')
    expect(page.locator('#preview-tested-count')).to_have_text('6')
    page.locator('canvas').click()
    expect(page.locator('#preview-tested-count')).to_have_text('6')
    page.locator('[data-panel="appearance"]').click()
    page.locator('[data-theme="night"]').click()
    page.wait_for_timeout(200)
    page.screenshot(path=str(OUT/'3d-keyboard-test.png'),full_page=True)
    page.locator('#typing').fill('打字体验不计入检测')
    expect(page.locator('#preview-test-status')).to_have_text('自动检测中')
    page.keyboard.press('x')
    expect(page.locator('#preview-tested-count')).to_have_text('6')
    page.locator('#scene').focus()
    page.keyboard.press('b')
    expect(page.locator('#preview-tested-count')).to_have_text('7')
    page.locator('#preview-clear-test').click()
    expect(page.locator('#preview-tested-count')).to_have_text('0')
    expect(page.locator('#tested-count')).to_have_text('0')
    page.keyboard.press('q')
    expect(page.locator('#preview-tested-count')).to_have_text('1')
    expect(page.locator('#preview-test-status')).to_have_text('自动检测中')
    page.locator('#preview-clear-test').click()
    page.locator('#reset-config').click()
    page.locator('[data-panel="appearance"]').click()
    for width in [390,768]:
        page.set_viewport_size({'width':width,'height':844})
        page.wait_for_timeout(300)
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'),f'page overflow at {width}'
        expect(page.locator('canvas')).to_be_visible()
        page.screenshot(path=str(OUT/f'mobile-{width}.png'),full_page=True)
    assert not errors,errors
    print('PASS: automatic detection on page entry, no start/pause controls, reset keeps detection active, typing exclusion with automatic resume; 104-key display, themes, structure, save/reload/export, left/right modifiers, numpad, rollover, repeat, blur recovery, responsive layout and shared 3D/2D records.')
    browser.close()
